import type { Locators, ReplayAssertion, ResolvedAction } from "./types";

/**
 * Render a compiled replay script as a standalone Playwright test. Locators
 * prefer getByRole and getByTestId; credentials become process.env reads
 * named by their placeholder keys, so the file never holds a secret.
 */

export interface SpecInput {
  testCaseName: string;
  steps: Array<{ action: string; expected: string }>;
  version: number;
  startUrl: string;
  actions: ResolvedAction[];
}

const PLACEHOLDER = /\{\{credential:([^}]+)\}\}/g;

const q = (value: string) => JSON.stringify(value);

function envRead(key: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? `process.env.${key} ?? ""` : `process.env[${q(key)}] ?? ""`;
}

/** A value with credential placeholders as an expression reading them from the environment. */
function valueExpr(value: string): string {
  const keys = Array.from(value.matchAll(PLACEHOLDER), (m) => m[1].trim());
  if (keys.length === 0) return q(value);
  const whole = value.match(/^\{\{credential:([^}]+)\}\}$/);
  if (whole) return envRead(whole[1].trim());
  const parts = value.split(PLACEHOLDER).map((part, i) =>
    i % 2 === 1 ? `\${${envRead(part.trim())}}` : part.replace(/[`\\$]/g, "\\$&")
  );
  return `\`${parts.join("")}\``;
}

function locatorExpr(locators: Locators | undefined): string | null {
  if (locators?.role) return `page.getByRole(${q(locators.role.role)}, { name: ${q(locators.role.name)}, exact: true })`;
  if (locators?.testId) return `page.getByTestId(${q(locators.testId)})`;
  if (locators?.css) return `page.locator(${q(locators.css)})`;
  if (locators?.text) return `page.getByText(${q(locators.text)}, { exact: true })`;
  return null;
}

function looksLikeCss(ref: string): boolean {
  return /^[#.[]|^[a-z]+(\[|#|\.|:|\s*>)/.test(ref);
}

function elementRef(assertion: ReplayAssertion): string {
  const ref = assertion.selector ?? assertion.expected;
  return looksLikeCss(ref) ? `page.locator(${q(ref)}).first()` : `page.getByText(${q(ref)}).first()`;
}

function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function assertionLine(assertion: ReplayAssertion): string {
  const { type, expected } = assertion;
  switch (type) {
    case "text_contains":
      return `await expect(page.locator("body")).toContainText(${q(expected)});`;
    case "url_matches":
      return `await expect(page).toHaveURL(new RegExp(${q(escapeRegex(expected))}));`;
    case "element_exists":
      return `await expect(${elementRef(assertion)}).toBeAttached();`;
    case "attribute_equals":
      return `await expect(page.locator(${q(assertion.selector ?? "")}).first()).toHaveAttribute(${q(assertion.attribute ?? "")}, ${q(expected)});`;
    case "element_count":
      return `await expect(page.locator(${q(assertion.selector ?? "")})).toHaveCount(${Number.parseInt(expected, 10)});`;
    case "accessibility_check":
      return `await expect(${elementRef(assertion)}).toBeVisible(); // Orbit also checks this element's accessibility`;
    default:
      return `await expect(${elementRef(assertion)}).toBeVisible();`;
  }
}

function actionLines(action: ResolvedAction): string[] {
  // compileRecording guarantees element actions carry a locator
  const target = locatorExpr(action.locators) ?? `page.locator(":root")`;
  switch (action.action) {
    case "navigate":
      return [`await page.goto(new URL(${valueExpr(action.url ?? "/")}, START_URL).toString());`];
    case "click":
      return [`await ${target}.click();`];
    case "fill":
      return [`await ${target}.fill(${valueExpr(action.valueRef ?? "")});`];
    case "select":
      return [`await ${target}.selectOption(${valueExpr(action.valueRef ?? "")});`];
    case "hover":
      return [`await ${target}.hover();`];
    case "press_key":
      return [`await page.keyboard.press(${q(action.valueRef ?? "Enter")});`];
    case "scroll":
      return [`await page.mouse.wheel(0, 300);`];
    default:
      return [];
  }
}

export function renderPlaywrightSpec(input: SpecInput): string {
  const skipsLogin = input.actions.some((a) => a.action === "skip_auth");
  const body: string[] = [];
  for (const action of input.actions) {
    const step = input.steps[action.stepIndex];
    body.push(`  // Step ${action.stepIndex + 1}: ${step?.action ?? action.action} (expected: ${step?.expected ?? ""})`);
    if (action.action === "skip_auth") {
      body.push("  // Login step: the session from ORBIT_STORAGE_STATE is already signed in.");
      continue;
    }
    for (const line of actionLines(action)) body.push(`  ${line}`);
    if (action.post.assertion) body.push(`  ${assertionLine(action.post.assertion)}`);
  }

  return [
    `// Generated by Orbit from replay script v${input.version} of ${q(input.testCaseName)}.`,
    "// Credentials are read from environment variables; Orbit never exports their values.",
    `import { test, expect } from "@playwright/test";`,
    "",
    `const START_URL = process.env.ORBIT_START_URL ?? ${q(input.startUrl)};`,
    ...(skipsLogin ? ["", "test.use({ storageState: process.env.ORBIT_STORAGE_STATE });"] : []),
    "",
    `test(${q(input.testCaseName)}, async ({ page }) => {`,
    "  await page.goto(START_URL);",
    ...body,
    "});",
    "",
  ].join("\n");
}
