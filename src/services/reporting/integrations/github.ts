import type { RunSummary } from "@/agents/schemas/run-summary";
import { resolveGitHubToken, getRepoInfo } from "@/lib/github/token";
import { upsertCheckRun } from "./github-checks";

interface PRCommentResult {
  success: boolean;
  commentId: string;
  prNumber: number;
  body: string;
}

interface CheckRunResult {
  success: boolean;
  checkRunId: string;
  commitSha: string;
  conclusion: "success" | "failure" | "neutral";
}

function formatRunSummaryAsMarkdown(summary: RunSummary, testedUrl?: string | null): string {
  const passRate =
    summary.totalTests > 0
      ? ((summary.passed / summary.totalTests) * 100).toFixed(1)
      : "0.0";

  const statusIcon = summary.failed > 0 ? "X" : "check";
  const durationSec = (summary.durationMs / 1000).toFixed(1);

  let md = `## Orbit Test Run [${statusIcon === "check" ? "PASSED" : "FAILED"}]\n\n`;
  md += `**${summary.totalTests}** tests | `;
  md += `**${summary.passed}** passed | `;
  md += `**${summary.failed}** failed | `;
  md += `**${summary.flaky}** flaky | `;
  md += `**${summary.skipped}** skipped\n\n`;
  md += `Pass rate: **${passRate}%** | Duration: **${durationSec}s** | Credits: **${summary.creditsConsumed}**\n\n`;
  if (testedUrl) md += `Tested against: ${testedUrl}\n\n`;
  md += `> ${summary.summary}\n`;

  if (summary.failures.length > 0) {
    md += `\n### Failures\n\n`;
    for (const failure of summary.failures) {
      md += `#### [${failure.severity.toUpperCase()}] ${failure.testName}\n`;
      md += `${failure.explanation}\n\n`;
      md += `**Suggested fix:** ${failure.suggestedFix}\n\n`;
    }
  }

  md += `\n---\n*Generated by [Orbit](https://orbitesting.com)*`;
  return md;
}

/**
 * Find an existing Orbit comment on a PR to update instead of creating a new one.
 */
async function findExistingOrbitComment(
  owner: string,
  repo: string,
  prNumber: number,
  token: string
): Promise<number | null> {
  const url = `https://api.github.com/repos/${owner}/${repo}/issues/${prNumber}/comments?per_page=100`;

  try {
    const response = await fetch(url, {
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
      },
    });

    if (!response.ok) return null;

    const comments = (await response.json()) as Array<{
      id: number;
      body: string;
    }>;

    // Find existing Orbit comment by our signature
    const orbitComment = comments.find(
      (c) =>
        c.body.includes("Orbit Test Run") &&
        c.body.includes("Generated by [Orbit]")
    );

    return orbitComment?.id ?? null;
  } catch {
    return null;
  }
}

export async function postPRComment(
  prNumber: number,
  summary: RunSummary,
  projectId?: string,
  testedUrl?: string | null
): Promise<PRCommentResult> {
  const body = formatRunSummaryAsMarkdown(summary, testedUrl);

  if (!projectId) {
    console.warn("[github] No projectId provided, skipping PR comment");
    return { success: false, commentId: "", prNumber, body };
  }

  const resolved = await resolveGitHubToken(projectId);
  if (!resolved) {
    console.warn("[github] No GitHub token available, skipping PR comment");
    return { success: false, commentId: "", prNumber, body };
  }

  const repoInfo = await getRepoInfo(projectId);
  if (!repoInfo) {
    console.warn("[github] No repo info found, skipping PR comment");
    return { success: false, commentId: "", prNumber, body };
  }

  const { token } = resolved;

  try {
    const existingId = await findExistingOrbitComment(
      repoInfo.owner,
      repoInfo.repo,
      prNumber,
      token
    );

    let url: string;
    let method: string;

    if (existingId) {
      // Update existing comment
      url = `https://api.github.com/repos/${repoInfo.owner}/${repoInfo.repo}/issues/comments/${existingId}`;
      method = "PATCH";
    } else {
      // Create new comment
      url = `https://api.github.com/repos/${repoInfo.owner}/${repoInfo.repo}/issues/${prNumber}/comments`;
      method = "POST";
    }

    const response = await fetch(url, {
      method,
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ body }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.warn(
        `[github] PR comment failed (${response.status}): ${errorText}`
      );
      return { success: false, commentId: "", prNumber, body };
    }

    const data = (await response.json()) as { id: number };
    return {
      success: true,
      commentId: String(data.id),
      prNumber,
      body,
    };
  } catch (error) {
    console.warn("[github] PR comment request failed:", error);
    return { success: false, commentId: "", prNumber, body };
  }
}

export async function createCheckRun(
  commitSha: string,
  summary: RunSummary,
  projectId?: string,
  testedUrl?: string | null
): Promise<CheckRunResult> {
  const conclusion: CheckRunResult["conclusion"] =
    summary.failed > 0 ? "failure" : "success";

  if (!projectId) {
    console.warn("[github] No projectId provided, skipping check run");
    return { success: false, checkRunId: "", commitSha, conclusion };
  }

  const checkRunId = await upsertCheckRun(projectId, {
    name: "Orbit Test Run",
    commitSha,
    status: "completed",
    conclusion,
    title: `Orbit: ${summary.passed}/${summary.totalTests} passed`,
    summary: formatRunSummaryAsMarkdown(summary, testedUrl),
  });
  return { success: !!checkRunId, checkRunId: checkRunId ?? "", commitSha, conclusion };
}

export { formatRunSummaryAsMarkdown };
export type { PRCommentResult, CheckRunResult };
