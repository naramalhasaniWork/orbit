import { prisma } from "@/lib/db";
import type { RunSummary } from "@/agents/schemas/run-summary";

interface PRCommentResult {
  success: boolean;
  commentId: string;
  prNumber: number;
  body: string;
}

interface CheckRunResult {
  success: boolean;
  checkRunId: string;
  commitSha: string;
  conclusion: "success" | "failure" | "neutral";
}

function formatRunSummaryAsMarkdown(summary: RunSummary): string {
  const passRate =
    summary.totalTests > 0
      ? ((summary.passed / summary.totalTests) * 100).toFixed(1)
      : "0.0";

  const statusIcon = summary.failed > 0 ? "X" : "check";
  const durationSec = (summary.durationMs / 1000).toFixed(1);

  let md = `## Orbit Test Run [${statusIcon === "check" ? "PASSED" : "FAILED"}]\n\n`;
  md += `**${summary.totalTests}** tests | `;
  md += `**${summary.passed}** passed | `;
  md += `**${summary.failed}** failed | `;
  md += `**${summary.flaky}** flaky | `;
  md += `**${summary.skipped}** skipped\n\n`;
  md += `Pass rate: **${passRate}%** | Duration: **${durationSec}s** | Credits: **${summary.creditsConsumed}**\n\n`;
  md += `> ${summary.summary}\n`;

  if (summary.failures.length > 0) {
    md += `\n### Failures\n\n`;
    for (const failure of summary.failures) {
      md += `#### [${failure.severity.toUpperCase()}] ${failure.testName}\n`;
      md += `${failure.explanation}\n\n`;
      md += `**Suggested fix:** ${failure.suggestedFix}\n\n`;
    }
  }

  md += `\n---\n*Generated by [Orbit](https://orbitesting.com)*`;
  return md;
}

async function getGitHubToken(projectId: string): Promise<string | null> {
  const project = await prisma.project.findUnique({
    where: { id: projectId },
    select: {
      workspace: {
        select: {
          members: {
            select: {
              user: {
                select: {
                  accounts: {
                    where: { provider: "github" },
                    select: { access_token: true },
                    take: 1,
                  },
                },
              },
            },
            take: 1,
            orderBy: { createdAt: "asc" },
          },
        },
      },
    },
  });

  const token =
    project?.workspace?.members?.[0]?.user?.accounts?.[0]?.access_token;

  if (!token) {
    const envToken = process.env.GITHUB_TOKEN;
    return envToken ?? null;
  }

  return token;
}

async function getRepoInfo(
  projectId: string
): Promise<{ owner: string; repo: string } | null> {
  const project = await prisma.project.findUnique({
    where: { id: projectId },
    select: { repoOwner: true, repoName: true },
  });

  if (!project?.repoOwner || !project?.repoName) return null;
  return { owner: project.repoOwner, repo: project.repoName };
}

export async function postPRComment(
  prNumber: number,
  summary: RunSummary,
  projectId?: string
): Promise<PRCommentResult> {
  const body = formatRunSummaryAsMarkdown(summary);

  if (!projectId) {
    console.warn("[github] No projectId provided, skipping PR comment");
    return { success: false, commentId: "", prNumber, body };
  }

  const token = await getGitHubToken(projectId);
  if (!token) {
    console.warn("[github] No GitHub token configured, skipping PR comment");
    return { success: false, commentId: "", prNumber, body };
  }

  const repoInfo = await getRepoInfo(projectId);
  if (!repoInfo) {
    console.warn("[github] No repo info found, skipping PR comment");
    return { success: false, commentId: "", prNumber, body };
  }

  const url = `https://api.github.com/repos/${repoInfo.owner}/${repoInfo.repo}/issues/${prNumber}/comments`;

  try {
    const response = await fetch(url, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ body }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.warn(
        `[github] PR comment failed (${response.status}): ${errorText}`
      );
      return { success: false, commentId: "", prNumber, body };
    }

    const data = (await response.json()) as { id: number };
    return {
      success: true,
      commentId: String(data.id),
      prNumber,
      body,
    };
  } catch (error) {
    console.warn("[github] PR comment request failed:", error);
    return { success: false, commentId: "", prNumber, body };
  }
}

export async function createCheckRun(
  commitSha: string,
  summary: RunSummary,
  projectId?: string
): Promise<CheckRunResult> {
  const conclusion: CheckRunResult["conclusion"] =
    summary.failed > 0 ? "failure" : "success";

  if (!projectId) {
    console.warn("[github] No projectId provided, skipping check run");
    return { success: false, checkRunId: "", commitSha, conclusion };
  }

  const token = await getGitHubToken(projectId);
  if (!token) {
    console.warn("[github] No GitHub token configured, skipping check run");
    return { success: false, checkRunId: "", commitSha, conclusion };
  }

  const repoInfo = await getRepoInfo(projectId);
  if (!repoInfo) {
    console.warn("[github] No repo info found, skipping check run");
    return { success: false, checkRunId: "", commitSha, conclusion };
  }

  const markdownSummary = formatRunSummaryAsMarkdown(summary);
  const url = `https://api.github.com/repos/${repoInfo.owner}/${repoInfo.repo}/check-runs`;

  try {
    const response = await fetch(url, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        name: "Orbit Test Run",
        head_sha: commitSha,
        status: "completed",
        conclusion,
        output: {
          title: `Orbit: ${summary.passed}/${summary.totalTests} passed`,
          summary: markdownSummary,
        },
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.warn(
        `[github] Check run failed (${response.status}): ${errorText}`
      );
      return { success: false, checkRunId: "", commitSha, conclusion };
    }

    const data = (await response.json()) as { id: number };
    return {
      success: true,
      checkRunId: String(data.id),
      commitSha,
      conclusion,
    };
  } catch (error) {
    console.warn("[github] Check run request failed:", error);
    return { success: false, checkRunId: "", commitSha, conclusion };
  }
}

export { formatRunSummaryAsMarkdown };
export type { PRCommentResult, CheckRunResult };
